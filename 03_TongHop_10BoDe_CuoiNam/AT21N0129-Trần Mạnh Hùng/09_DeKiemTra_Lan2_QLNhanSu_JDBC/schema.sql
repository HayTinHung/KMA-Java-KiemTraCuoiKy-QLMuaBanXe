/* CSDL cho Kiểm tra lần 2 - Đề 1. Chạy bằng SSMS hoặc sqlcmd. */
IF DB_ID(N'QLNhanSu') IS NULL
    CREATE DATABASE QLNhanSu;
GO

USE QLNhanSu;
GO

IF OBJECT_ID(N'dbo.Cap', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.Cap (
        MaCap INT NOT NULL CONSTRAINT PK_Cap PRIMARY KEY,
        Ten NVARCHAR(50) NOT NULL,
        BaoHiem INT NOT NULL,
        CONSTRAINT UQ_Cap_Ten UNIQUE (Ten),
        CONSTRAINT CK_Cap_Ten CHECK (LEN(LTRIM(RTRIM(Ten))) > 0),
        CONSTRAINT CK_Cap_BaoHiem CHECK (BaoHiem BETWEEN 0 AND 100)
    );
END;
GO

IF OBJECT_ID(N'dbo.NhanSu', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.NhanSu (
        MNS INT NOT NULL CONSTRAINT PK_NhanSu PRIMARY KEY,
        TNS NVARCHAR(50) NOT NULL,
        TienLuong INT NOT NULL,
        MaCap INT NOT NULL,
        CONSTRAINT CK_NhanSu_MNS CHECK (MNS BETWEEN 1 AND 99999),
        CONSTRAINT CK_NhanSu_TNS CHECK (LEN(LTRIM(RTRIM(TNS))) > 0),
        CONSTRAINT CK_NhanSu_TienLuong CHECK (TienLuong > 0),
        CONSTRAINT FK_NhanSu_Cap FOREIGN KEY (MaCap) REFERENCES dbo.Cap(MaCap)
    );
END;
GO

IF NOT EXISTS (SELECT 1 FROM dbo.Cap)
BEGIN
    /* Dùng UTF-16LE dạng hex để sqlcmd không làm hỏng tiếng Việt theo code page. */
    INSERT INTO dbo.Cap (MaCap, Ten, BaoHiem) VALUES
        (1, CONVERT(nvarchar(50), 0x51007500A31E6E0020006C00FD00), 16),
        (2, CONVERT(nvarchar(50), 0x4C00E3006E00680020001101A11E6F00), 12),
        (3, CONVERT(nvarchar(50), 0x5400E100630020006E00670068006900C71E7000), 8);
END;
GO

/* Sửa dữ liệu mẫu cũ nếu schema được chạy bằng sqlcmd với code page không phải UTF-8. */
UPDATE dbo.Cap SET Ten = CONVERT(nvarchar(50), 0x51007500A31E6E0020006C00FD00)
WHERE MaCap = 1 AND Ten = CONVERT(nvarchar(50), 0x51007500E100BA00A3006E0020006C00C300BD00);
UPDATE dbo.Cap SET Ten = CONVERT(nvarchar(50), 0x4C00E3006E00680020001101A11E6F00)
WHERE MaCap = 2 AND Ten = CONVERT(nvarchar(50), 0x4C00C300A3006E0068002000C4001820E100BA00A1006F00);
UPDATE dbo.Cap SET Ten = CONVERT(nvarchar(50), 0x5400E100630020006E00670068006900C71E7000)
WHERE MaCap = 3 AND Ten = CONVERT(nvarchar(50), 0x5400C300A100630020006E00670068006900E100BB0021207000);
GO
